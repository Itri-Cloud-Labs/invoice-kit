import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const vendorOutput = join(projectRoot, "dist", "vendor");

const packageRoot = (packageName) => dirname(require.resolve(`${packageName}/package.json`));

const pdfkitRoot = packageRoot("pdfkit");
const dejavuRoot = packageRoot("dejavu-fonts-ttf");

await mkdir(vendorOutput, { recursive: true });

await Promise.all([
  copyFile(join(pdfkitRoot, "js", "pdfkit.standalone.js"), join(vendorOutput, "pdfkit.cjs")),
  copyFile(join(pdfkitRoot, "LICENSE"), join(vendorOutput, "PDFKit-LICENSE.txt")),
  copyFile(join(dejavuRoot, "LICENSE"), join(vendorOutput, "DejaVu-LICENSE.txt"))
]);

const [regularFont, boldFont] = await Promise.all([
  readFile(join(dejavuRoot, "ttf", "DejaVuSans.ttf")),
  readFile(join(dejavuRoot, "ttf", "DejaVuSans-Bold.ttf"))
]);

const fontModule = `"use strict";
// Generated by scripts/prepare-runtime-assets.mjs. See DejaVu-LICENSE.txt.
module.exports = Object.freeze({
  regular: ${JSON.stringify(regularFont.toString("base64"))},
  bold: ${JSON.stringify(boldFont.toString("base64"))}
});
`;

await writeFile(join(vendorOutput, "dejavu-fonts.cjs"), fontModule);
